// Generates styles.css from palette.mjs. Run: bun build.mjs
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { dark, light } from "./palette.mjs";

const rgbChannels = (hex) => {
  const value = hex.replace("#", "");
  return [0, 2, 4].map((offset) => parseInt(value.slice(offset, offset + 2), 16));
};

const rgb = (hex) => rgbChannels(hex).join(" ");

const hsl = (hex) => {
  const [r, g, b] = rgbChannels(hex).map((channel) => channel / 255);
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const lightness = (max + min) / 2;
  let hue = 0;
  let saturation = 0;
  if (max !== min) {
    const delta = max - min;
    saturation = lightness > 0.5 ? delta / (2 - max - min) : delta / (max + min);
    if (max === r) hue = (g - b) / delta + (g < b ? 6 : 0);
    else if (max === g) hue = (b - r) / delta + 2;
    else hue = (r - g) / delta + 4;
    hue *= 60;
  }
  const round = (number) => Math.round(number * 10) / 10;
  return `${round(hue)} ${round(saturation * 100)}% ${round(lightness * 100)}%`;
};

const kebab = (key) => key.replace(/[A-Z]/g, (char) => `-${char.toLowerCase()}`);

const declarations = (palette) => {
  const lines = [];
  for (const [stop, hex] of Object.entries(palette.slate)) lines.push(`--slate-${stop}-rgb: ${rgb(hex)};`);
  for (const [stop, hex] of Object.entries(palette.accent)) lines.push(`--brand-green-${stop}-rgb: ${rgb(hex)};`);
  const { brand } = palette;
  lines.push(
    `--brand-green: ${brand.base};`,
    `--brand-green-hover: ${brand.hover};`,
    `--brand-green-muted: ${brand.muted};`,
    `--brand-green-soft: ${brand.soft};`,
    `--brand-green-border: ${brand.border};`,
    `--brand-green-text: ${brand.text};`,
    `--brand-green-rgb: ${rgb(brand.base)};`,
    `--brand-green-hover-rgb: ${rgb(brand.hover)};`,
  );
  for (const [key, hex] of Object.entries(palette.workspace)) lines.push(`--workspace-${kebab(key)}: ${hex};`);
  lines.push(
    `--tooltip-bg: ${palette.tooltip.bg};`,
    `--tooltip-fg: ${palette.tooltip.fg};`,
    `--tooltip-border: ${palette.tooltip.border};`,
    `--switch-thumb: ${palette.controls.switchThumb};`,
    `--switch-track-on: ${palette.controls.switchTrackOn};`,
    `--switch-thumb-on: ${palette.controls.switchThumbOn};`,
    `--checkbox-on: ${palette.controls.checkboxOn};`,
    `--checkbox-mark: ${palette.controls.checkboxMark};`,
    `--search-match: ${palette.search.match};`,
    `--search-match-active: ${palette.search.active};`,
    `--scrollbar-thumb: ${palette.scrollbar.thumb};`,
    `--scrollbar-thumb-hover: ${palette.scrollbar.hover};`,
    `--dark-surface-rgb: ${rgb(palette.darkSurface)};`,
    `--memo-content-divider-color: ${palette.memoContentDivider};`,
    `--blue-600-rgb: ${rgb(palette.accent[600])};`,
  );
  for (const [key, hex] of Object.entries(palette.shadcn)) lines.push(`--${kebab(key)}: ${hsl(hex)};`);
  return lines.map((line) => `  ${line}`).join("\n");
};

const css = `/* Fjord theme for EdgeEver. Generated by build.mjs from palette.mjs; do not edit by hand.
 * Overrides EdgeEver's color custom properties. The light block uses :root, which beats the
 * layered defaults; the dark block repeats EdgeEver's :root.dark selector and wins by load order. */

:root {
${declarations(light)}
}

:root.dark {
${declarations(dark)}
}
`;

const outputPath = join(dirname(fileURLToPath(import.meta.url)), "styles.css");
writeFileSync(outputPath, css);
console.log(`Wrote ${outputPath}`);
